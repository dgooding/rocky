#!/usr/bin/env bash
# Build a macOS .app bundle that launches the app from this repository.
# The bundle is what gives macOS a stable identity for camera/microphone
# permission. Do not use `exec` in the launcher.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP="$ROOT/Rocky.app"
CONTENTS="$APP/Contents"
MACOS="$CONTENTS/MacOS"
LAUNCHER="$MACOS/Rocky"

if [[ ! -x "$ROOT/venv/bin/python" ]]; then
  echo "WARNING: $ROOT/venv/bin/python not found. Run ./setup.sh first." >&2
fi

rm -rf "$APP"
mkdir -p "$MACOS"

cat > "$CONTENTS/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleDisplayName</key><string>Rocky</string>
  <key>CFBundleExecutable</key><string>Rocky</string>
  <key>CFBundleIdentifier</key><string>com.aiserver.rocky</string>
  <key>CFBundleName</key><string>Rocky</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1.0</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <key>NSCameraUsageDescription</key>
  <string>Rocky opens the camera for a moment to see what you are holding.</string>
  <key>NSMicrophoneUsageDescription</key>
  <string>Rocky listens through the microphone so you can talk to him.</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

cat > "$LAUNCHER" <<LAUNCH
#!/bin/bash
# Generated by scripts/make_app.sh — do not use exec here.
ROOT="$ROOT"
cd "\$ROOT" || exit 1
LOG="\$HOME/Library/Logs/Rocky.log"
mkdir -p "\$(dirname "\$LOG")"
echo "--- \$(date '+%Y-%m-%d %H:%M:%S') launch ---" >>"\$LOG"
./venv/bin/python rocky_desktop_app.py "\$@" >>"\$LOG" 2>&1
exit \$?
LAUNCH

chmod +x "$LAUNCHER"

if command -v codesign >/dev/null 2>&1; then
  if codesign --force --sign - --identifier com.aiserver.rocky "$APP" 2>/dev/null; then
    echo "Ad-hoc signed: com.aiserver.rocky"
  else
    echo "WARNING: ad-hoc codesign failed; the app may still run." >&2
  fi
fi

echo
echo "Built: $APP"
echo "Launch: open -n \"$APP\""
echo
echo "If macOS asks for camera/microphone permission, allow it once."
echo "If you move the repository, rebuild this bundle."
